                                    <li><strong>Tinjauan lapangan</strong> — peninjauan lokasi untuk memastikan kesesuaian rencana tapak (jika belum sesuai, berkas dikembalikan untuk revisi).</li>
                                    <li><strong>Penandatanganan gambar site plan</strong> — siteplan yang telah sesuai ditandatangani oleh pejabat berwenang.</li>
                                    <li><strong>Registrasi dan pengarsipan</strong> — siteplan yang telah disahkan diregistrasi dan diarsipkan sebagai dokumen resmi.</li>
                                    <li><strong>Menghubungi pemohon</strong> — pemohon dihubungi untuk mengambil dokumen siteplan yang sudah disahkan.</li>
