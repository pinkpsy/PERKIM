                            <div class="faq-content">
                                <p>Prosesnya melalui 6 tahapan:</p>
                                <ol class="mb-0">
                                    <li><strong>Pemohon memasukkan berkas</strong> — mengajukan permohonan beserta kelengkapan dokumen.</li>
