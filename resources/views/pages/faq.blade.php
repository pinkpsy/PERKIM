                                    <li>Fotokopi legalitas perusahaan (NIB)</li>
                                    <li>Fotokopi Izin Lokasi (bila ada)</li>
                                    <li>Fotokopi Surat Keterangan Rencana Kabupaten (KRK) dari DPUPR Kab. HST</li>
                                    <li>Fotokopi Sertifikat Tanah/Sporadik</li>
                                    <li>Fotokopi dan file peta bidang tanah/gambar hasil ukur dari Kantor Pertanahan (format DWG dan SHP)</li>
                                    <li>Fotokopi Izin Lingkungan (SPPL, UKL-UPL, AMDAL) bila diperlukan</li>
